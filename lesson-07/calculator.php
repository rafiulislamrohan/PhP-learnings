<?php

function add($a , $b){
    return $a+$b;
}
function subtract($a , $b){
    return $a-$b;
}
function multiply($a , $b){
    return $a*$b;
}
function divide($a , $b){
    return $a/$b;
}

echo "addition : " . add(20 , 5);
echo "<br>";
echo "subtract : " . subtract(20 , 5);
echo "<br>";
echo "multiply : " . multiply(20 , 5);
echo "<br>";
echo "divide : " . divide(20 , 5);



?>